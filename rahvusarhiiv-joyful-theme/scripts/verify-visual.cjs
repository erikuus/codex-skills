/* Render with render-probe.php first. PLAYWRIGHT_MODULE and CHROME_PATH may select local installations. */
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('node:fs');const path=require('node:path');const assert=require('node:assert/strict');
(async()=>{
 const skill=path.resolve(__dirname,'..');const theme=path.join(skill,'assets/app/themes/joyful');
 if(!process.argv[2])throw new Error('Supply the HTML file generated by render-probe.php');
 const html=fs.readFileSync(process.argv[2],'utf8');
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
 try{
  const pages=[];
  for(const legacy of [true,false]){
   const page=await browser.newPage();
   await page.route('http://joyful.local/**',async route=>{
    const name=new URL(route.request().url()).pathname;
    if(name==='/'){
     let markup=html.replace('<head>','<head><link rel="stylesheet" href="/themes/joyful/css/style.css">');
     if(legacy)for(const variant of ['first','last','odd','hover']) for(const el of ['tr','th','td']) markup=markup.replaceAll('prose-'+el+':'+variant+':',variant+':prose-'+el+':');
     return route.fulfill({contentType:'text/html',body:markup});
    }
    let file=path.join(theme,name.replace('/themes/joyful/',''));
    if(legacy && name.endsWith('/style.css'))file=path.join(skill,'assets/reference/vau-frozen.css');
    if(!file.startsWith(theme) && !file.startsWith(path.join(skill,'assets/reference')))return route.abort();
    if(!fs.existsSync(file))return route.abort();
    return route.fulfill({path:file});
   });
   await page.goto('http://joyful.local/');await page.evaluate(()=>document.fonts.ready);pages.push(page);
  }
  async function metrics(page){return page.evaluate(()=>{
   const css=selector=>getComputedStyle(document.querySelector(selector));
   const shadow=selector=>css(selector).boxShadow.replaceAll('rgba(0, 0, 0, 0) 0px 0px 0px 0px, ','');
   const rect=selector=>document.querySelector(selector).getBoundingClientRect();
   return {
    headers:[...document.querySelectorAll('header')].map(e=>e.getBoundingClientRect().height),
    containerWidth:rect('main').width,contentPadding:css('main').paddingTop,
    radius:css('body > div').borderBottomLeftRadius,shadow:shadow('body > div'),
    gradient:css('.bg-theme-vau').backgroundImage,bodyFont:css('body').fontFamily,
    headerFontSize:css('#probe-grid th').fontSize,cellPadding:css('#probe-grid td').paddingTop,
    firstCellRadius:css('#probe-grid tbody tr:first-child td:first-child').borderTopLeftRadius,
    stripe:css('#probe-grid tbody tr:first-child').backgroundColor,
    tableShadow:shadow('main .prose'),
    crumbFontSize:css('nav[aria-label] ol').fontSize,
    homeBackground:css('nav[aria-label] ol li a').backgroundColor,
    homeWidth:rect('nav[aria-label] ol li a').width,
    breadcrumbInGradient:!!document.querySelector('nav[aria-label] ol').closest('.bg-theme-vau'),
    breadcrumbAboveWhitePanel:rect('nav[aria-label]').bottom <= rect('main').top,
    overflow:document.documentElement.scrollWidth>innerWidth,
    svg:rect('#probe-grid .view svg').width,
    pagerFont:css('#probe-grid .pager').fontSize,
   };
  });}
  for(const width of [390,768,1024,1440,1600]){
   for(const p of pages)await p.setViewportSize({width,height:1000});
   const expected=await metrics(pages[0]), actual=await metrics(pages[1]);
   for(const key of Object.keys(expected)){
    if(key==='overflow')assert.equal(actual[key],false,'no page overflow at '+width);
    else assert.deepEqual(actual[key],expected[key],key+' differs from original CSS at '+width);
   }
   assert.equal(actual.breadcrumbInGradient,true);assert.equal(actual.breadcrumbAboveWhitePanel,true);
   assert.equal(actual.radius,'8px');assert.equal(actual.cellPadding,'12px');assert.equal(actual.svg,20);
   console.log('PASS visual source parity at '+width+'px (layout, tokens, breadcrumb, grid, pager)');
  }
  await pages[1].locator('#probe-grid tbody tr').first().hover();
  assert.equal(await pages[1].locator('#probe-grid tbody tr').first().evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(233, 247, 238)');
  await pages[1].evaluate(() => { window.feedbackCalls=[]; window.open=(...args)=>feedbackCalls.push(args); });
  await pages[1].getByRole('button',{name:'Tagasiside',exact:true}).click();
  assert.equal(await pages[1].evaluate(()=>feedbackCalls[0][0]),'https://www.ra.ee/vau/index.php/helpdesk/message/feedback?language=et&dialog=1&url=');
  console.log('PASS exact footer feedback popup behavior');
  if(process.env.JOYFUL_SCREENSHOT_DIR){
   fs.mkdirSync(process.env.JOYFUL_SCREENSHOT_DIR,{recursive:true});
   for(const width of [390,1440]){
    await pages[1].setViewportSize({width,height:1000});await pages[1].mouse.move(0,0);
    await pages[1].screenshot({path:path.join(process.env.JOYFUL_SCREENSHOT_DIR,'probe-'+width+'.png'),fullPage:true});
   }
  }
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
